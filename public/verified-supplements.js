function normalizeSearchTerm(value) {
  const normalized = String(value || "").normalize("NFC").trim().replace(/\s+/g, " ");
  return /[A-Za-z]/u.test(normalized) && !/[가-힣]/u.test(normalized)
    ? normalized.toLocaleLowerCase("en")
    : normalized;
}

export function findVerifiedSupplements(value) {
  const term = normalizeSearchTerm(value);
  if (!term) return [];
  return VERIFIED_SUPPLEMENTS.filter((item) => item.searchTerms.includes(term));
}

export function getVerifiedSupplementCount() {
  return VERIFIED_SUPPLEMENTS.length;
}

function normalizePartOfSpeech(value) {
  return String(value || "").trim().toLocaleLowerCase("en");
}

const SUMMARY_GLOSS_STOP_WORDS = new Set([
  "a", "an", "and", "any", "as", "at", "be", "by", "for", "from", "his", "her", "in",
  "into", "is", "its", "of", "on", "or", "the", "their", "to", "used", "with"
]);
const MIN_SUMMARY_TRANSLATION_MATCH = 0.5;
const MIN_SUMMARY_TRANSLATION_MARGIN = 0.12;

function normalizeSummaryGloss(value) {
  return String(value || "")
    .split(/\s+[—–-]\s+(?:see(?:\s+also)?|compare)\b/i, 1)[0]
    .toLocaleLowerCase("en")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function summaryGlossTokens(value) {
  return normalizeSummaryGloss(value)
    .split(" ")
    .filter((token) => token.length > 1 && !SUMMARY_GLOSS_STOP_WORDS.has(token));
}

function summaryTranslationMatchScore(definitionText, sourceSense) {
  const definition = normalizeSummaryGloss(definitionText);
  const sense = normalizeSummaryGloss(sourceSense);
  if (!definition || !sense) return 0;
  if (definition === sense) return 1;
  if (definition.includes(sense) || sense.includes(definition)) return 0.92;

  const definitionTokens = new Set(summaryGlossTokens(definition));
  const senseTokens = new Set(summaryGlossTokens(sense));
  if (!definitionTokens.size || !senseTokens.size) return 0;
  let shared = 0;
  for (const token of senseTokens) {
    if (definitionTokens.has(token)) shared += 1;
  }
  return shared / Math.sqrt(definitionTokens.size * senseTokens.size);
}

function inferTranslationDefinitionGroup(entry, translation) {
  const definitionGroups = (entry?.definitionGroups || []).filter(
    (group) => normalizePartOfSpeech(group.partOfSpeech)
  );
  const partOfSpeechKeys = new Set(
    definitionGroups.map((group) => normalizePartOfSpeech(group.partOfSpeech))
  );
  if (partOfSpeechKeys.size === 1) return definitionGroups[0] || null;
  if (!translation?.sense) return null;

  const scoresByPartOfSpeech = new Map();
  for (const group of definitionGroups) {
    const key = normalizePartOfSpeech(group.partOfSpeech);
    const score = Math.max(
      0,
      ...(group.definitions || []).map((definition) =>
        summaryTranslationMatchScore(definition.text, translation.sense)
      )
    );
    const previous = scoresByPartOfSpeech.get(key);
    if (!previous || score > previous.score) scoresByPartOfSpeech.set(key, { group, score });
  }

  const scores = [...scoresByPartOfSpeech.values()]
    .sort((left, right) => right.score - left.score);
  const best = scores[0];
  const runnerUp = scores[1];
  if (
    !best ||
    best.score < MIN_SUMMARY_TRANSLATION_MATCH ||
    (runnerUp && best.score - runnerUp.score < MIN_SUMMARY_TRANSLATION_MARGIN)
  ) return null;
  return best.group;
}

export function buildMeaningSummaryGroups(entry, supplements = []) {
  const groups = [];
  const groupsByPartOfSpeech = new Map();

  function ensureGroup(partOfSpeech, partOfSpeechKo) {
    const key = normalizePartOfSpeech(partOfSpeech) || "unclassified";
    if (!groupsByPartOfSpeech.has(key)) {
      const group = {
        partOfSpeech: partOfSpeech || "",
        partOfSpeechKo: partOfSpeechKo || "",
        meanings: []
      };
      groupsByPartOfSpeech.set(key, group);
      groups.push(group);
    }
    const group = groupsByPartOfSpeech.get(key);
    if (!group.partOfSpeechKo && partOfSpeechKo) group.partOfSpeechKo = partOfSpeechKo;
    return group;
  }

  function addMeaning(group, meaning) {
    const existing = group.meanings.find((item) => item.term === meaning.term);
    if (!existing) {
      group.meanings.push(meaning);
      return;
    }
    if (meaning.verified) {
      existing.verified = true;
      existing.supplementId = meaning.supplementId;
    }
  }

  if (entry?.language === "en") {
    for (const definitionGroup of entry.definitionGroups || []) {
      const group = ensureGroup(definitionGroup.partOfSpeech, definitionGroup.koreanLabel);
      for (const definition of definitionGroup.definitions || []) {
        for (const translation of definition.koreanTranslations || []) {
          addMeaning(group, {
            term: translation.term,
            sense: translation.sense || "",
            verified: false,
            supplementId: null
          });
        }
      }
    }

    for (const definitionGroup of entry.definitionGroups || []) {
      const group = ensureGroup(definitionGroup.partOfSpeech, definitionGroup.koreanLabel);
      if (!group.meanings.length) {
        for (const translation of definitionGroup.summaryKoreanTranslations || []) {
          addMeaning(group, {
            term: translation.term,
            sense: translation.sense || "",
            verified: false,
            supplementId: null
          });
        }
      }
    }

    const ungrouped = (entry.translations || []).filter(
      (translation) => !groups.some((group) =>
        group.meanings.some((meaning) => meaning.term === translation.term)
      )
    );
    for (const translation of ungrouped) {
      const definitionGroup = inferTranslationDefinitionGroup(entry, translation);
      const group = definitionGroup
        ? ensureGroup(definitionGroup.partOfSpeech, definitionGroup.koreanLabel)
        : ensureGroup("", "");
      addMeaning(group, {
        term: translation.term,
        sense: translation.sense || "",
        verified: false,
        supplementId: null
      });
    }
  }

  for (const supplement of supplements) {
    const group = ensureGroup(
      supplement.english.partOfSpeech,
      supplement.english.partOfSpeechKo
    );
    addMeaning(group, {
      term: entry?.language === "ko"
        ? supplement.english.headword
        : supplement.korean.headword,
      sense: "",
      verified: true,
      supplementId: supplement.id
    });
  }

  return groups.filter((group) => group.meanings.length);
}

function makeElement(document, tag, className, text) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  if (text !== undefined) element.textContent = text;
  return element;
}

function makeLink(document, href, text) {
  const link = makeElement(document, "a", "", text);
  link.href = href;
  link.target = "_blank";
  link.rel = "noreferrer";
  return link;
}

export function renderMeaningSummary(container, entry, supplements = []) {
  const groups = buildMeaningSummaryGroups(entry, supplements);
  container.replaceChildren();
  const document = container.ownerDocument;
  const targetLanguage = entry?.language === "ko" ? "en" : "ko";

  groups.forEach((group, index) => {
    const section = makeElement(document, "section", "translation-group");
    const headingId = `translation-group-${index + 1}`;
    const label = group.partOfSpeechKo
      ? `${group.partOfSpeechKo} · ${group.partOfSpeech}`
      : group.partOfSpeech;
    if (label) {
      const heading = makeElement(document, "h3", "translation-group-label", label);
      heading.setAttribute("id", headingId);
      section.setAttribute("aria-labelledby", headingId);
      section.append(heading);
    } else {
      section.setAttribute("aria-label", "뜻");
    }

    const items = makeElement(document, "div", "translation-group-items");
    for (const meaning of group.meanings) {
      const item = makeElement(document, "span", "translation-item", meaning.term);
      item.setAttribute("lang", targetLanguage);
      if (meaning.sense) {
        const sense = makeElement(document, "small", "", meaning.sense);
        sense.setAttribute("title", meaning.sense);
        item.append(sense);
      }
      if (meaning.verified) {
        item.className += " is-verified";
      }
      items.append(item);
    }
    section.append(items);
    container.append(section);
  });

  return {
    groupCount: groups.length,
    meaningCount: groups.reduce((sum, group) => sum + group.meanings.length, 0),
    title: entry?.language === "ko" ? "연결된 영어 뜻" : "한국어 뜻"
  };
}

function makeSupplementCard(document, supplement) {
  const card = makeElement(document, "article", "verified-supplement-card");
  card.dataset.supplementId = supplement.id;
  const koreanDefinition = makeElement(document, "p", "supplement-definition", supplement.korean.definition);
  const details = makeElement(document, "details", "supplement-source-details");
  const summary = makeElement(document, "summary", "supplement-source-summary", "출처 보기");
  const source = makeElement(document, "div", "supplement-source");
  const sourceText = makeElement(document, "div", "");
  sourceText.append(
    makeElement(document, "strong", "", supplement.korean.sourceName),
    makeElement(
      document,
      "span",
      "",
      `표제어 ${supplement.korean.entryId} · 뜻 ${supplement.korean.senseId}`
    )
  );
  const sourceLinks = makeElement(document, "div", "supplement-source-links");
  sourceLinks.append(
    makeLink(document, supplement.korean.sourceUrl, "한국어 원문 보기 ↗"),
    makeLink(document, supplement.korean.license.url, supplement.korean.license.name),
    makeLink(
      document,
      supplement.english.sourceUrl,
      `영어 원뜻 보기 · ${supplement.english.sourceName || "Wiktionary"} 리비전 ${supplement.english.revisionId} ↗`
    ),
    makeLink(
      document,
      supplement.english.license?.url || "https://creativecommons.org/licenses/by-sa/4.0/",
      supplement.english.license?.name || "CC BY-SA 4.0"
    )
  );
  source.append(sourceText, sourceLinks);
  details.append(summary, source);
  card.append(koreanDefinition, details);
  return card;
}

export function renderVerifiedSupplements(container, value) {
  const supplements = findVerifiedSupplements(value);
  container.replaceChildren();
  if (!supplements.length) return 0;

  const document = container.ownerDocument;
  const section = makeElement(document, "div", "verified-supplements-section");
  section.setAttribute("aria-label", "뜻 설명과 출처");

  for (const supplement of supplements) {
    section.append(makeSupplementCard(document, supplement));
  }
  container.append(section);
  return supplements.length;
}
